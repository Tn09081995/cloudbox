// Relative date helper so "Hôm nay", "Hôm qua", and dates group realistically
function getRelativeDate(hoursAgo: number): string {
  const d = new Date();
  d.setMinutes(d.getMinutes() - Math.floor(hoursAgo * 60));
  return d.toISOString();
}

function getDaysAgo(days: number, hour = 14, minute = 30): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

